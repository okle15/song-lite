/**
 * 曲目标记的**共享契约**：收藏与屏蔽。零业务依赖。
 *
 * ── 为什么这两件事要落库（而不是留在浏览器里）───────────────────────
 * 收藏与屏蔽在此之前（或原本）属于「本机状态」：收藏活在前端
 * `localStorage`（`LS_KEYS.favorites`），于是**服务端与 agent 完全不知道
 * 用户收藏了什么**。而按本项目的分类判据（见 `agent/prompt.ts` 与
 * `AGENTS.md` 的 ⑦ 分流规则）：
 *
 *     音量 / 播放方式 = **设备的事实**（这台浏览器多大声）→ 服务端只配镜像；
 *     收藏 / 屏蔽     = **人的偏好**（我喜欢什么、我不想听什么）→ 服务端是真相。
 *
 * 「人的偏好不进服务端，agent 就永远是瞎的」——它既答不了「我收藏了哪些」，
 * 也没法说「这首帮你收起来了」。所以这两件事必须落库。
 *
 * ── 两种标记的语义（不是同一个东西的两个值）─────────────────────────
 * `favorite` = 「我想多听」；`hidden` = 「我不想听」。
 * 它们**可以同时为真**（先收藏、后来听腻了屏蔽），所以是两张表、不是一列
 * 二值枚举 —— 合成一张表只会让「这行为什么在」必须看列才知道。
 */

/** 两种标记的名字。**取值的全集只在这里一处**，加第三种时不会漏掉某一侧。 */
export type FlagKind = 'favorite' | 'hidden';

/**
 * 说给人听的说法（工具返回值 / 界面文案 / 提示词）。
 * 与 `contract/player.ts` 的 `PLAYBACK_MODE_LABEL` 同一个位置、同一个理由：
 * 一处定义、多处消费，避免「服务端说'已收藏'、界面写'已加入喜欢'」这种漂移。
 */
export const FLAG_LABEL: Record<FlagKind, { name: string; verb: string; done: string; undone: string }> = {
	favorite: { name: '收藏', verb: '收藏', done: '已收藏', undone: '已取消收藏' },
	hidden: { name: '屏蔽', verb: '屏蔽', done: '已屏蔽', undone: '已解除屏蔽' },
};

/**
 * 一个标记对应的一行 —— 两条路由（`/api/library/{favorites,hidden}`）的响应形状。
 *
 * ⚠️ `title` / `artist` 是**服务端按 trackId 现查**填上的，不是库里的冗余：
 * 曲库不落库（真相在文件系统），所以标记表里只存 id。按 id 现查的代价是
 * 每次列表都要扫一遍全库 —— 本曲库 6 首，可以忽略。
 */
export type FlagRow = {
	/** `Song.id`（曲库内相对路径）。 */
	trackId: string;
	title: string;
	artist: string;
	/**
	 * 这首歌的**文件已经不在曲库里了**（被删 / 改名 / 移走）。
	 *
	 * 必须单独一个字段、不许只留个空标题：改名 = 新 id（路径寻址的固有性质，
	 * 见 `server/library/scanner.ts`），于是「收藏过一首后来改名的歌」会变成
	 * 一行没有歌的标记。用户看到它时该明白那是**自己的收藏失效了**，
	 * 而不是「界面坏了」。这也是为什么它照旧列出来、不静默过滤掉。
	 */
	missing: boolean;
};

/*
 * 这里**故意没有**「合并两份 id」的函数。
 *
 * 老版本把收藏存在 `localStorage`，迁移到服务端时看起来需要它 —— 但
 * `setFlag(id, true)` 本身幂等（同 id 再写只是无操作），所以"逐个打上"
 * 就等于取并集，不需要先算差集。早先写过一个 `mergeFlagIds()`，
 * 删掉它的理由就是项目里那条老规矩：**没有消费者的通用机制是负债** ——
 * 它唯一能待的地方是一段注释（就是这段）。
 */
