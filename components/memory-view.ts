/**
 * 「记忆」卡的纯规则 —— 提出来的原因和 `approval-view.ts`、`toolCallPruningFor()` 一样：
 * **它是那种「写错了不报错、只是让人看到一幅看着正常其实骗人的画面」的规则。**
 *
 * ── 为什么这张卡非要不可 ──────────────────────────────────────────
 * ⑥ 记忆是 `LEARNING.md` 说的「唯一不会被模型换代抹平的东西」。它的写入由模型判断
 * （铁律 6），注入到**以后每一次对话**。而 `prompt.ts` 里那条铁律的原文自己写着：
 *
 *     **记错比不记更糟**：它会长期影响以后每一次对话，而用户不知道你记了什么。
 *
 * 「用户不知道」被写成了风险，可产品上一直没有出口 —— `GET /api/preferences`
 * 这条路 2026-09-2x 就在，`app/api/preferences/route.ts` 的文件头甚至提前写下了
 * 「将来前端加一个「管理我的偏好」面板，走的是同一条路径、同一套校验、同一个信封」，
 * 而那个面板直到今天才做。所以这张卡不是新功能，是**把已经存在的能力接上出口**
 * （与阶段 3c 那次「路由本来就存在、缺的只是工具」同一个形状）。
 *
 * ── 抽出来的那两条规则 ─────────────────────────────────────────────
 * 两条都不报错，且都会让人**照着一个假结论去行动**：
 *
 *   1. 「读不到」被画成「还没记住什么」。两件事都渲染成一块没有内容的区域，
 *      但一件是「它确实没记」，另一件是「我现在看不到」。合成一个的话，用户会得出
 *      「我从来没设过偏好」——而真实情况是 agent 正拿着一个他看不见的东西影响每一轮
 *      对话。**这正是这张卡要消灭的那个处境本身**，不分开就等于卡片自己犯了它要修的错。
 *   2. 「服务端拒绝」与「网络没通」合成一句「没删掉」。都是没删掉，但下一步不同：
 *      前者说明请求到了、是发出去的东西有问题，再点一次也是一样的结果；后者值得重试。
 */
import type { Preference } from '@/contract/preference';

/**
 * 卡片当前该画哪一幅。
 *
 * `list` 带回 `items` 本身（而不是让渲染侧再读一次状态），这样四态与数据**同源**，
 * 不会出现「状态说有条目、数据还是空的」那种中间帧。
 */
export type MemoryView =
	| { kind: 'loading' }
	| { kind: 'error' }
	| { kind: 'empty' }
	| { kind: 'list'; items: Preference[] };

export function memoryView(input: {
	/** 第一次请求是否已经出结果（成功或失败都算）。 */
	loaded: boolean;
	/** 读取失败时的一句人话；成功时为 `null`。 */
	error: string | null;
	items: Preference[];
}): MemoryView {
	// ⚠️ **`error` 的判断必须排在 `empty` 前面**，这条顺序是承重的。
	// 反过来写（先看有没有条目）时，读失败与空列表都会落到 `empty`，
	// 于是「看不到」被显示成「没记住」—— 用户据此得不出「要不要再试一次」的答案，
	// 只会得出一个关于自己的错误结论。单测里有一条专门钉这个顺序。
	if (input.error !== null) return { kind: 'error' };
	if (!input.loaded) return { kind: 'loading' };
	if (input.items.length === 0) return { kind: 'empty' };
	return { kind: 'list', items: input.items };
}

/**
 * 删除没成功时那句提示。`status` 传 `null` 表示请求根本没发出去（网络层失败）。
 *
 * 为什么不合成一句「删除失败」：这两件事对用户的**下一步**不同。服务端回了 4xx/5xx
 * 说明请求到了、是我们发的东西不被接受（再点一次同样结果），网络没通则值得重试。
 * 症状一样、修法相反 —— 与 ⑨ 归因把「环境类」和「行为类」分开是同一条判据
 * （见 `server/agent/diagnose.ts`）。
 */
export function forgetFailed(status: number | null): string {
	return status === null
		? '没删掉（网络没通）—— 这条还在。'
		: `没删掉（服务端回了 ${status}）—— 这条还在。`;
}
